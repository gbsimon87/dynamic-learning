import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { CURRICULUM_YEARS, CURRICULUM_SUBJECTS, loadCurriculum } from "../../src/data/curriculumRegistry.js";
import { REPO_ROOT, findMapping, repoPath, wrapperPaths } from "./topics.js";

export function buildJourneyManifest({ years = CURRICULUM_YEARS, subjects = CURRICULUM_SUBJECTS, load = loadCurriculum,
  isBuilt = (year, subject, topicId, challengeId) => existsSync(repoPath(REPO_ROOT,
    wrapperPaths({ year, subject, topicId })[Number(challengeId) - 1])) } = {}) {
  const pathways = [];
  for (const year of years) for (const { id: subject } of subjects) {
    const curriculum = load(year, subject);
    if (!curriculum) continue;
    const categories = curriculum.map((category) => ({ id: category.id,
      topics: category.topics.map((topic) => ({ id: topic.id,
        challengeIds: topic.challenges.filter((challenge) => isBuilt(year, subject, topic.id, challenge.id)).map((c) => Number(c.id)),
      })).filter((topic) => topic.challengeIds.length),
    })).filter((category) => category.topics.length);
    if (categories.length) pathways.push({ year, subject, categories });
  }
  return pathways;
}

export function journeyManifestSource(manifest) {
  return `// Generated by npm run journey:manifest -- --write. Do not edit IDs here.\nexport const CURRICULUM_JOURNEY_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
}

// Each built topic's saved statutory mapping row: the file and its nearest
// heading. Authored banks/introductions cite these instead of hand-typed paths.
export function buildJourneySources(manifest, { root = REPO_ROOT } = {}) {
  const sources = {};
  for (const pathway of manifest) for (const quest of pathway.categories) for (const topic of quest.topics) {
    const { file, rows } = findMapping({ root, year: pathway.year, subject: pathway.subject, topicId: topic.id });
    if (!rows.length) throw new Error(`No statutory mapping row for ${pathway.year}/${pathway.subject}/${topic.id}`);
    sources[`${pathway.year}/${pathway.subject}/${topic.id}`] = { path: file, heading: rows[0].heading.split(" > ").at(-1), topicId: topic.id };
  }
  return sources;
}

export function journeySourcesSource(sources) {
  return `// Generated by npm run journey:manifest -- --write from docs/curriculum mapping rows.\nexport const CURRICULUM_JOURNEY_SOURCES = ${JSON.stringify(sources, null, 2)};\n`;
}

export function manifestTotals(manifest) {
  const totals = { pathways: manifest.length, quests: 0, topics: 0, challenges: 0 };
  for (const pathway of manifest) for (const quest of pathway.categories) {
    totals.quests++;
    totals.topics += quest.topics.length;
    totals.challenges += quest.topics.reduce((sum, topic) => sum + topic.challengeIds.length, 0);
  }
  return { ...totals, introductions: totals.pathways + totals.quests + totals.topics,
    assessments: totals.pathways + totals.quests, minimumCandidates: totals.topics * 3 };
}

export function runManifestCommand(args) {
  const { values, positionals } = parseArgs({ args, options: { write: { type: "boolean" }, check: { type: "boolean" } } });
  if (positionals.length || Number(Boolean(values.write)) + Number(Boolean(values.check)) !== 1) {
    throw new Error("Choose exactly one of --write or --check");
  }
  const manifest = buildJourneyManifest();
  const outputs = [["shared/curriculumJourneyManifest.js", journeyManifestSource(manifest)],
    ["shared/curriculumJourneySources.js", journeySourcesSource(buildJourneySources(manifest))]];
  for (const [relative, output] of outputs) {
    const file = repoPath(REPO_ROOT, relative);
    if (values.write) writeFileSync(file, output);
    else if (!existsSync(file) || readFileSync(file, "utf8") !== output) throw new Error(`${relative} is stale. Run npm run journey:manifest -- --write`);
  }
  return manifestTotals(manifest);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { console.log(JSON.stringify(runManifestCommand(process.argv.slice(2)), null, 2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
