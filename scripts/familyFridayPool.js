// Create a NEW publication snapshot, never rewrite an existing bank. This is
// developer tooling for content releases, not a weekly publishing dependency.
import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { CURRICULUM_JOURNEY_MANIFEST } from '../shared/curriculumJourneyManifest.js';
import { loadCurriculumAssessmentBank } from '../shared/curriculumAssessments/index.js';
import { validateAssessmentCandidate } from '../shared/curriculumAssessmentData.js';

const plain = text => text.replace(/\*\*/g, '').trim();

/** Fail closed: a choice must carry all its context in a short prompt. */
export function adaptFamilyQuestion(item, year, subject) {
  const { prompt, model, evidence, input } = item.public;
  if (model || evidence.length || input.kind !== 'choice' || input.options.length < 3) return null;
  if (prompt.split(/\s+/).length > 45 || /\b(?:picture|diagram|chart|table|passage|extract|above|below|shown|underlined|highlighted|listen)\b/i.test(prompt)) return null;
  if (item.scoring.accepted.length !== 1) return null;
  const answer = input.options.find(option => option.id === item.scoring.accepted[0])?.label;
  if (!answer) return null;
  const options = [answer, ...input.options.filter(option => option.label !== answer).slice(0, 2).map(option => option.label)].map(plain);
  if (options.some(option => !option || option.length > 120) || new Set(options.map(option => option.toLowerCase())).size !== 3) return null;
  return {
    id: `curriculum:${year}:${subject}:${item.id}`, prompt: plain(prompt), answer: plain(answer), options,
    explanation: plain(item.review.explanation),
    curriculum: { year, subject, topicId: item.topicId, challengeId: item.practice.challengeId, itemId: item.id, sourceRefs: item.sourceRefs },
  };
}

export async function curriculumFamilyPool() {
  const questions = [], seen = new Set();
  for (const { year, subject } of CURRICULUM_JOURNEY_MANIFEST) {
    const bank = await loadCurriculumAssessmentBank(year, subject);
    if (!bank) throw new Error(`Missing curriculum assessment bank: ${year}/${subject}`);
    for (const item of bank.items) {
      validateAssessmentCandidate(item);
      const question = adaptFamilyQuestion(item, year, subject);
      if (!question) continue;
      const key = JSON.stringify([question.prompt, question.answer, [...question.options].sort()]);
      if (!seen.has(key)) { questions.push(question); seen.add(key); }
    }
  }
  return questions;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const destination = process.argv[2];
  if (!destination) throw new Error('Usage: node scripts/familyFridayPool.js <NEW-bank.js>');
  const questions = await curriculumFamilyPool();
  if (!questions.length) throw new Error('No eligible curriculum questions');
  const content = '// Immutable publication snapshot, generated by scripts/familyFridayPool.js.\n'
    + '// Add a new dated bank instead of regenerating this file.\nexport default [\n'
    + questions.map(question => `  ${JSON.stringify(question)},`).join('\n') + '\n];\n';
  await writeFile(destination, content, { flag: 'wx' });
  console.log(`Saved ${questions.length} curriculum questions to ${destination}`);
}
