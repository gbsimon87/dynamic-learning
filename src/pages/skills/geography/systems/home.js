function homePlanet(planet) {
    const details = PLANET_DETAILS[planet.name];
    return {
        ...planet,
        id: planet.name,
        spokenName: planet.name,
        kindLabel: planet.name === "Pluto" ? "Dwarf planet" : "Planet",
        ...(planet.name === "Pluto" ? { classification: "Dwarf planet" } : {}),
        // Earth's Moon has its own play numbers and Moon phases section.
        moons: planet.moons.map((moon) => (planet.name === "Earth" && moon.name === "Moon"
            ? { ...moon, play: PLANET_PLAY.Moon, sections: { moonPhases: true } }
            : moon)),
        facts: details.facts,
        closer: details.closer,
        play: PLANET_PLAY[planet.name],
        lineUp: Boolean(TRUE_RADII_KM[planet.name]),
        ...(SECTIONS[planet.name] ? { sections: SECTIONS[planet.name] } : {}),
    };
}

