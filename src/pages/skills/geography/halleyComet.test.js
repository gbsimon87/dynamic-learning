import test from 'node:test';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createHalleyComet } from './halleyComet.js';

test('comet follows shared clock, hides in other modes, switches quality and disposes', () => {
    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera();
    camera.position.set(0, 70, 120);
    let time = 0;
    let hidden = false;
    let quality = 'standard';
    const comet = createHalleyComet({ scene, getCamera: () => camera, getOrbitTime: () => time, getQuality: () => quality, isHidden: () => hidden });
    comet.update(0);
    const start = comet.object3d.position.clone();
    const tails = () => comet.object3d.children.filter(c => c.name.includes('tail'));
    const before = tails()[0].geometry.attributes.position.array.slice();
    comet.update(1);
    assert.deepEqual(comet.object3d.position, start);
    assert.deepEqual(tails()[0].geometry.attributes.position.array, before);
    time = 10;
    comet.update(0);
    assert.ok(comet.object3d.position.distanceTo(start) > 1);
    hidden = true;
    comet.update(0);
    assert.equal(comet.object3d.visible, false);
    hidden = false;
    comet.update(0, { active: true });
    assert.equal(comet.object3d.visible, false);
    comet.update(0, { active: false });
    assert.equal(comet.object3d.visible, true);
    const old = tails()[0].geometry;
    let disposed = false;
    old.addEventListener('dispose', () => { disposed = true; });
    quality = 'low'; comet.resize(); comet.update(0);
    assert.equal(disposed, true);
    assert.ok(tails()[0].geometry.attributes.position.count < old.attributes.position.count);
    assert.ok([...tails()[0].geometry.attributes.position.array].every(Number.isFinite));
    comet.dispose();
    assert.equal(scene.children.length, 0);
});
