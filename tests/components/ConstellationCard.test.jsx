import React from 'react';
import { render, screen, fireEvent, cleanup } from '@testing-library/react';
import { afterEach, expect, test, vi } from 'vitest';
import ConstellationCard from '../../src/pages/skills/geography/ConstellationCard.jsx';
import { constellations } from '../../src/pages/skills/geography/constellations.js';
import { speak, stopNarration } from '../../src/utils/speech.js';
import { isMuted } from '../../src/components/celebration/sound/player.js';
vi.mock('../../src/utils/speech.js', () => ({ speak: vi.fn(), stopNarration: vi.fn() }));
vi.mock('../../src/components/celebration/sound/player.js', () => ({ isMuted: vi.fn(() => false) }));
afterEach(() => { cleanup(); vi.clearAllMocks(); });
const props = { constellation: constellations[0], index: 0, total: 5, muted: false, onPrevious: vi.fn(), onNext: vi.fn(), onToggleMute: vi.fn(), onExit: vi.fn(), onFindSky: vi.fn() };
test('only the integrated sky is offered, with compact exclusive sections and navigation', () => {
  const { unmount } = render(<ConstellationCard {...props} />);
  expect(screen.queryByRole('img')).toBeNull();
  expect(screen.queryByText(/star chart/i)).toBeNull();
  expect(screen.getByRole('dialog').getAttribute('aria-modal')).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Centre constellation' }));
  expect(props.onFindSky).toHaveBeenCalledOnce();
  fireEvent.click(screen.getByRole('button', { name: /About this pattern/ }));
  expect(screen.getByText(/not tonight’s sky/)).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: /Star facts/ }));
  expect(screen.queryByText(/not tonight’s sky/)).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: 'Next', exact: true }));
  expect(props.onNext).toHaveBeenCalledOnce();
  fireEvent.keyDown(window, { key: 'Escape' }); expect(props.onExit).toHaveBeenCalledOnce();
  unmount(); expect(stopNarration).toHaveBeenCalled();
});
test('site mute and explorer mute suppress sky teaching narration', () => {
  isMuted.mockReturnValue(true);
  const { rerender } = render(<ConstellationCard {...props} />);
  expect(speak).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: 'Replay narration' }));
  expect(speak).not.toHaveBeenCalled();
  isMuted.mockReturnValue(false);
  rerender(<ConstellationCard {...props} muted />);
  expect(screen.getByRole('button', { name: 'Replay narration' }).disabled).toBe(true);
});
